#!/usr/bin/env python3
"""Module for simple_add function."""


def add(a, b):
    """Return the sum of two numbers.

    Args:
        a (int/float): First number.
        b (int/float): Second number.

    Returns:
        int/float: The sum.
    """
    return a + b


if __name__ == "__main__":
    print(add(3, 5))
